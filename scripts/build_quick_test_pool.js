addBatch(existingHist, 'تاریخ و تمدن باستان', 'history');
addBatch(motivationalTexts, 'موفقیت، ذهن و انگیزه', 'motivation');
addBatch(wisdomAndTales, 'حکمت و شاهکارهای ادب کهن', 'wisdom');
addBatch(futureTechTexts, 'فناوری و جهان آینده', 'tech');
addBatch(earthAndNatureTexts, 'شگفتی‌های زمین و طبیعت', 'nature');

// Save to frontend/src/data/quickTestPool.json
const targetPath = path.resolve(__dirname, '../frontend/src/data/quickTestPool.json');
fs.writeFileSync(targetPath, JSON.stringify(allTexts, null, 2), 'utf-8');


// Combine all into a final unified collection (Total = 120 + 60 + 60 + 60 + 60 = 360 pristine texts!)
const allTexts = [];
let idCounter = 1;

function addBatch(items, topicName, cat) {
  for (const item of items) {
    const textStr = typeof item === 'string' ? item : item.text;
    const finalTopic = typeof item === 'object' && item.topic ? item.topic : topicName;
    const finalCat = typeof item === 'object' && item.category ? item.category : cat;
    allTexts.push({
      id: `quick-${String(idCounter++).padStart(3, '0')}`,
      topic: finalTopic,
      category: finalCat,
      text: textStr.trim(),
      charCount: textStr.trim().length,
      wordCount: textStr.trim().split(/\s+/).length,
      difficulty: textStr.length > 140 ? 'پیشرفته' : textStr.length > 90 ? 'متوسط' : 'آسان',
      language: 'fa'
    });
  }
}


// 3. Update frontend/src/data/typingPool.json
const poolPath = path.resolve('frontend/src/data/typingPool.json');
let existingPool = [];
try {
  existingPool = JSON.parse(fs.readFileSync(poolPath, 'utf8'));
} catch (e) {
  existingPool = [];
}

const existingTextsSet = new Set(existingPool.map(i => i.text));
let addedToPool = 0;

for (const t of textsData) {
  if (!existingTextsSet.has(t.text)) {
    existingPool.push({
      id: `rich-typing-${existingPool.length + 1}`,
      language: 'fa',
      category: 'fa',
      subCategory: t.category,
      difficulty: t.difficulty,
      title: t.title,
      text: t.text
    });
    existingTextsSet.add(t.text);
    addedToPool++;
  }
}

fs.writeFileSync(poolPath, JSON.stringify(existingPool, null, 2), 'utf8');
console.log(`Added ${addedToPool} new texts to frontend typingPool.json (Total now: ${existingPool.length})`);
